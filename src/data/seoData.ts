/**
 * Helper to get metadata config for any pathname and language
 */
export function getRouteMeta(pathname: string, language: Language = 'bs'): RouteMetaConfig {
  const cleanPath = pathname.split('?')[0].split('#')[0].replace(/\/$/, '') || '/';
  const resolvedPath = ROUTE_ALIASES[cleanPath] || cleanPath;
  const routeConfig = MULTILINGUAL_ROUTE_META[resolvedPath] || MULTILINGUAL_ROUTE_META['/'];
  return routeConfig[language] || routeConfig['bs'] || routeConfig['en'];
}
